def break_monoalphabetic_cipher(ciphertext):
    # English letter frequency, from most to least common
    english_frequency = "ETAOINSHRDLCUMWFGYPBVKJXQZ"

    # Count letters in the ciphertext
    counts = Counter(
        ch.upper() for ch in ciphertext if ch.isalpha()
    )

    # Sort ciphertext letters by frequency
    cipher_order = [
        letter for letter, _ in counts.most_common()
    ]

    # Map frequent ciphertext letters to frequent English letters
    mapping = {}
    for i, letter in enumerate(cipher_order):
        if i < len(english_frequency):
            mapping[letter] = english_frequency[i]

    # Decrypt using the estimated mapping
    plaintext = ""
    for ch in ciphertext:
        if ch.isalpha():
            decoded = mapping.get(ch.upper(), ch.upper())
            plaintext += decoded.lower() if ch.islower() else decoded
        else:
            plaintext += ch

    print("Ciphertext:", ciphertext)
    print("Estimated plaintext:", plaintext)
    print("Substitution mapping:", mapping)


