def ioc(text):
    n = len(text)
    freq = [text.count(c) for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"]
    return sum(f * (f - 1) for f in freq) / (n * (n - 1)) if n > 1 else 0


def break_vigenere(cipher):
    text = ''.join(c for c in cipher.upper() if c.isalpha())

    # Estimate key length
    key_len = 1
    for k in range(1, 11):
        streams = [text[i::k] for i in range(k)]
        avg = sum(ioc(s) for s in streams) / k
        if avg > 0.055:
            key_len = k
            break

    # Recover key using frequency analysis
    freq = "ETAOINSHRDLCUMWFGYPBVKJXQZ"
    key = ""

    for i in range(key_len):
        stream = text[i::key_len]
        shift = max(range(26),
                    key=lambda s: sum(stream.count(chr((ord(c)-65+s)%26+65)) for c in freq[:1]))
        key += chr(shift + 65)

    # Decrypt
    result = ""
    j = 0
    for c in cipher:
        if c.isalpha():
            base = ord('A') if c.isupper() else ord('a')
            shift = ord(key[j % key_len]) - 65
            result += chr((ord(c) - base - shift) % 26 + base)
            j += 1
        else:
            result += c

    return key, result


