class Point:
    def __init__(self, x=None, y=None, is_infinity=False):
        self.x = x
        self.y = y
        self.is_infinity = is_infinity

    def __str__(self):
        if self.is_infinity:
            return "Point at Infinity (O)"
        return f"({self.x}, {self.y})"

    def __eq__(self, other):
        if self.is_infinity and other.is_infinity:
            return True
        if self.is_infinity != other.is_infinity:
            return False
        return self.x == other.x and self.y == other.y


class EllipticCurve:
    def __init__(self, a, b, p):
        self.a = a
        self.b = b
        self.p = p
        self.O = Point(is_infinity=True)

        discriminant = (4 * (a**3) + 27 * (b**2)) % p
        if discriminant == 0:
            raise ValueError("The chosen parameters (a, b) result in a singular curve.")

    def is_on_curve(self, point):
        if point.is_infinity:
            return True
        left_side = (point.y ** 2) % self.p
        right_side = (point.x ** 3 + self.a * point.x + self.b) % self.p
        return left_side == right_side

    def add(self, P, Q):
        if P.is_infinity:
            return Q
        if Q.is_infinity:
            return P

        if P.x == Q.x and (P.y + Q.y) % self.p == 0:
            return self.O

        if P == Q:
            if P.y == 0:
                return self.O
            numerator = (3 * (P.x ** 2) + self.a) % self.p
            denominator = (2 * P.y) % self.p

        else:
            numerator = (Q.y - P.y) % self.p
            denominator = (Q.x - P.x) % self.p

        lamb = (numerator * pow(denominator, -1, self.p)) % self.p

        x3 = (lamb ** 2 - P.x - Q.x) % self.p
        y3 = (lamb * (P.x - x3) - P.y) % self.p

        return Point(x3, y3)

    def scalar_multiply(self, k, P):
        if k == 0 or P.is_infinity:
            return self.O

        result = self.O
        addend = P

        while k > 0:
            if k % 2 != 0:
                result = self.add(result, addend)
            addend = self.add(addend, addend)
            k //= 2

        return result

