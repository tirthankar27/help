    ps = b'\0' * (k - 8 - 32 - 8 - 1)
    db = ps + b'\x01' + salt

    mask = mgf1(mh, k - 32 - 1)
    masked = bytes(a ^ b for a, b in zip(db, mask))

    em = masked + mh + b'\xbc'
    sig = pow(int.from_bytes(em, 'big'), d, n)

    return sig

